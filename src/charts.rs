//! Native Rust chart generator using [`plotters`].
//!
//! Replaces Python's `matplotlib` dependency across `cause_grapher.py`,
//! `csmf_grapher.py`, and `output_prep.py`, rendering all SmartVA PNG figures
//! (`*-csmf-figure.png`, `all-figure.png`, `undetermined-figure.png`, and
//! `gbd-level1-csmf.png`) in `3-graphs-and-tables/` at the exact 960x720
//! (`6.4x4.8 in @ 150 DPI`) resolution and visual layout of upstream SmartVA.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use plotters::prelude::*;
use plotters::style::text_anchor::{HPos, Pos, VPos};

const COLOR_MALE_OR_CSMF: RGBColor = RGBColor(0xC4, 0x44, 0x40); // #C44440
const COLOR_FEMALE: RGBColor = RGBColor(0x1D, 0x72, 0xAA); // #1D72AA
const GRID_COLOR: RGBColor = RGBColor(0xB0, 0xB0, 0xB0);

const AGE_BINS: &[&str] = &[
    "0-28 days",
    "29 days - 1 year",
    "1-4 years",
    "5-11 years",
    "12-19 years",
    "20-29 years",
    "30-39 years",
    "40-49 years",
    "50-59 years",
    "60-69 years",
    "70-79 years",
    "80+ years",
];

fn age_bin_index(module: &str, age_val: f64) -> usize {
    if module == "neonate" {
        return 0;
    }
    let years = age_val;
    if years >= 80.0 {
        11
    } else if years >= 70.0 {
        10
    } else if years >= 60.0 {
        9
    } else if years >= 50.0 {
        8
    } else if years >= 40.0 {
        7
    } else if years >= 30.0 {
        6
    } else if years >= 20.0 {
        5
    } else if years >= 12.0 {
        4
    } else if years >= 5.0 {
        3
    } else if years >= 1.0 {
        2
    } else if years >= (29.0 / 365.0) {
        1
    } else {
        0
    }
}

/// Render all SmartVA PNG figures in `3-graphs-and-tables/` using `plotters`.
pub fn generate_all_smartva_charts(output_dir: &Path, include_module_figures: bool) -> Result<usize> {
    let folder2 = output_dir.join("2-csmf");
    let folder3 = output_dir.join("3-graphs-and-tables");
    let folder1 = output_dir.join("1-individual-cause-of-death");
    fs::create_dir_all(&folder3).context("Failed to create 3-graphs-and-tables")?;

    let mut count = 0usize;

    // 1. Always generated by OutputPrep: `gbd-level1-csmf.png` and `all-csmf-figure.png`
    let gbd_csv = folder2.join("gbd-level1-csmf.csv");
    if gbd_csv.exists() {
        let gbd_rows = read_gbd_csmf(&gbd_csv)?;
        if !gbd_rows.is_empty() {
            render_gbd_pie_chart(&gbd_rows, &folder3.join("gbd-level1-csmf.png"))?;
            count += 1;
        }
    }

    let all_csmf_csv = folder2.join("csmf.csv");
    if all_csmf_csv.exists() {
        let pairs = read_csmf_column(&all_csmf_csv, 0, 2)?;
        if !pairs.is_empty() {
            render_csmf_bar_chart("All CSMF", &pairs, &folder3.join("all-csmf-figure.png"))?;
            count += 1;
        }
    }

    if !include_module_figures {
        return Ok(count);
    }

    // 2. Module CSMF charts (`adult`, `child`, `neonate`, `adult-male`, `adult-female`)
    for module in ["adult", "child", "neonate"] {
        let mod_csv = folder2.join(format!("{module}-csmf.csv"));
        if !mod_csv.exists() {
            continue;
        }
        // Columns in `2-csmf/{module}-csmf.csv`:
        // 0: cause34, 1: cause list #, 2: icd10, 3: all, 4: male, 5: female
        let both_pairs = read_csmf_column(&mod_csv, 0, 3)?;
        if !both_pairs.is_empty() {
            let title = format!("{}{} CSMF", module[..1].to_uppercase(), &module[1..]);
            render_csmf_bar_chart(
                &title,
                &both_pairs,
                &folder3.join(format!("{module}-csmf-figure.png")),
            )?;
            count += 1;
        }
        if module == "adult" {
            let male_pairs = read_csmf_column(&mod_csv, 0, 4)?;
            if male_pairs.iter().any(|(_, v)| *v > 0.0) {
                render_csmf_bar_chart(
                    "Adult-male CSMF",
                    &male_pairs,
                    &folder3.join("adult-male-csmf-figure.png"),
                )?;
                count += 1;
            }
            let female_pairs = read_csmf_column(&mod_csv, 0, 5)?;
            if female_pairs.iter().any(|(_, v)| *v > 0.0) {
                render_csmf_bar_chart(
                    "Adult-female CSMF",
                    &female_pairs,
                    &folder3.join("adult-female-csmf-figure.png"),
                )?;
                count += 1;
            }
        }
    }

    // 3. Age & Sex distribution bar charts (`all-figure.png` and `undetermined-figure.png`)
    let mut all_male = [0u32; 12];
    let mut all_female = [0u32; 12];
    let mut undet_male = [0u32; 12];
    let mut undet_female = [0u32; 12];
    let mut has_any = false;
    let mut has_undet = false;

    for module in ["adult", "child", "neonate"] {
        let pred_csv = folder1.join(format!("{module}-predictions.csv"));
        if !pred_csv.exists() {
            continue;
        }
        let mut rdr = csv::ReaderBuilder::new()
            .has_headers(true)
            .from_path(&pred_csv)?;
        // Headers in `1-individual-cause-of-death/{module}-predictions.csv`:
        // 0: sid, ..., 11: cause34, 12: cause list #, 13: icd10, 14: age, 15: sex
        for rec in rdr.records() {
            let row = rec?;
            let cause = row.get(11).unwrap_or("").trim();
            let age_str = row.get(14).unwrap_or("").trim();
            let sex_str = row.get(15).unwrap_or("").trim();
            let Ok(age_val) = age_str.parse::<f64>() else {
                continue;
            };
            let sex_code: i32 = sex_str.parse().unwrap_or(0);
            let bin = age_bin_index(module, age_val);
            if sex_code == 1 {
                all_male[bin] += 1;
                has_any = true;
                if cause.eq_ignore_ascii_case("Undetermined") {
                    undet_male[bin] += 1;
                    has_undet = true;
                }
            } else if sex_code == 2 {
                all_female[bin] += 1;
                has_any = true;
                if cause.eq_ignore_ascii_case("Undetermined") {
                    undet_female[bin] += 1;
                    has_undet = true;
                }
            }
        }
    }

    if has_any {
        render_age_sex_bar_chart(
            "All by age and sex",
            &all_male,
            &all_female,
            &folder3.join("all-figure.png"),
        )?;
        count += 1;
    }
    if has_undet {
        render_age_sex_bar_chart(
            "Undetermined by age and sex",
            &undet_male,
            &undet_female,
            &folder3.join("undetermined-figure.png"),
        )?;
        count += 1;
    }

    Ok(count)
}

fn read_csmf_column(
    csv_path: &Path,
    cause_col: usize,
    val_col: usize,
) -> Result<Vec<(String, f64)>> {
    let mut rdr = csv::ReaderBuilder::new()
        .has_headers(true)
        .from_path(csv_path)?;
    let mut pairs = Vec::new();
    for rec in rdr.records() {
        let row = rec?;
        let cause = row.get(cause_col).unwrap_or("").trim().to_string();
        let val: f64 = row
            .get(val_col)
            .unwrap_or("0")
            .trim()
            .parse()
            .unwrap_or(0.0);
        if !cause.is_empty() {
            pairs.push((cause, val));
        }
    }
    pairs.sort_by(|a, b| b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal));
    Ok(pairs)
}

fn read_gbd_csmf(csv_path: &Path) -> Result<Vec<(String, String, f64)>> {
    let mut rdr = csv::ReaderBuilder::new()
        .has_headers(true)
        .from_path(csv_path)?;
    let mut out = Vec::new();
    for rec in rdr.records() {
        let row = rec?;
        let code = row.get(0).unwrap_or("").trim().to_string();
        let name = row.get(1).unwrap_or("").trim().to_string();
        let val: f64 = row.get(2).unwrap_or("0").trim().parse().unwrap_or(0.0);
        if !code.is_empty() {
            out.push((code, name, val));
        }
    }
    Ok(out)
}

/// Render a vertical CSMF bar chart at 960x720 matching upstream `csmf_grapher.py`
/// (with 90°-rotated cause labels beneath each bar, major Y-gridlines, and `#C44440` bars).
pub fn render_csmf_bar_chart(
    title: &str,
    data: &[(String, f64)],
    out_path: &Path,
) -> Result<()> {
    let root = BitMapBackend::new(out_path, (960, 720)).into_drawing_area();
    root.fill(&WHITE)?;

    let max_val = data
        .iter()
        .map(|(_, v)| *v)
        .fold(0.0_f64, f64::max)
        .max(0.05);
    let y_top = max_val * 1.10;
    let n = data.len().max(1);

    // Match upstream `plt.subplots_adjust(bottom=0.60)`:
    // Upper ~310px is the plot box, lower ~410px holds the 90°-rotated cause names.
    let (upper, lower) = root.split_vertically(315);

    let left_margin = 95i32;
    let right_margin = 45i32;
    let top_margin = 55i32;

    let mut chart = ChartBuilder::on(&upper)
        .caption(title, ("sans-serif", 22).into_font())
        .margin_top(18)
        .margin_bottom(0)
        .margin_left(25)
        .margin_right(right_margin)
        .x_label_area_size(6)
        .y_label_area_size(70)
        .build_cartesian_2d(-0.5f64..((n as f64) + 0.5), 0f64..y_top)?;

    chart
        .configure_mesh()
        .disable_x_mesh()
        .max_light_lines(0)
        .bold_line_style(GRID_COLOR.mix(0.8))
        .y_desc("Mortality fractions")
        .y_labels(5)
        .axis_desc_style(("sans-serif", 18))
        .label_style(("sans-serif", 16))
        .x_labels(0)
        .draw()?;

    let bar_style = COLOR_MALE_OR_CSMF.filled();
    for (idx, (_, val)) in data.iter().enumerate() {
        let x0 = idx as f64 - 0.375;
        let x1 = idx as f64 + 0.375;
        chart.draw_series(std::iter::once(Rectangle::new(
            [(x0, 0.0), (x1, *val)],
            bar_style,
        )))?;
    }

    // Draw top and right plot frame lines to match matplotlib axes box
    let plot_left = left_margin;
    let plot_right = 960 - right_margin;
    let plot_top = top_margin;
    let plot_bottom = 309;
    upper.draw(&PathElement::new(
        vec![
            (plot_left, plot_top),
            (plot_right, plot_top),
            (plot_right, plot_bottom),
            (plot_left, plot_bottom),
            (plot_left, plot_top),
        ],
        BLACK.stroke_width(1),
    ))?;

    // Draw 90°-rotated X-axis ticks and cause names directly beneath each bar
    let x_span = (n as f64) + 1.0; // from -0.5 to n + 0.5
    let plot_w = (plot_right - plot_left) as f64;
    let v_font = ("sans-serif", 15)
        .into_font()
        .transform(FontTransform::Rotate270)
        .color(&BLACK)
        .pos(Pos::new(HPos::Right, VPos::Center));

    for (idx, (cause, _)) in data.iter().enumerate() {
        let frac = ((idx as f64) + 0.5) / x_span;
        let px = plot_left + (frac * plot_w).round() as i32;
        // Tick mark
        lower.draw(&PathElement::new(
            vec![(px, 0), (px, 5)],
            BLACK.stroke_width(1),
        ))?;
        // Rotated label reading bottom-to-top
        lower.draw(&Text::new(cause.as_str(), (px, 10), v_font.clone()))?;
    }

    root.present()?;
    Ok(())
}

/// Render a grouped Male vs Female age-distribution bar chart at 960x720
/// matching upstream `cause_grapher.py`.
pub fn render_age_sex_bar_chart(
    title: &str,
    male_counts: &[u32; 12],
    female_counts: &[u32; 12],
    out_path: &Path,
) -> Result<()> {
    let root = BitMapBackend::new(out_path, (960, 720)).into_drawing_area();
    root.fill(&WHITE)?;

    let max_count = male_counts
        .iter()
        .chain(female_counts.iter())
        .copied()
        .max()
        .unwrap_or(1)
        .max(1);
    let y_top = (max_count as f64) * 1.10;

    // Match upstream `plt.subplots_adjust(bottom=0.35)`:
    // Upper ~470px plot area, lower ~250px rotated age labels + bottom legend box.
    let (upper, lower) = root.split_vertically(470);

    let left_margin = 95i32;
    let right_margin = 45i32;
    let top_margin = 55i32;

    let mut chart = ChartBuilder::on(&upper)
        .caption(title, ("sans-serif", 22).into_font())
        .margin_top(18)
        .margin_bottom(0)
        .margin_left(25)
        .margin_right(right_margin)
        .x_label_area_size(6)
        .y_label_area_size(70)
        .build_cartesian_2d(-0.5f64..12.0f64, 0f64..y_top)?;

    chart
        .configure_mesh()
        .disable_x_mesh()
        .max_light_lines(0)
        .bold_line_style(GRID_COLOR.mix(0.8))
        .y_desc("Number of VAs")
        .y_labels(9)
        .y_label_formatter(&|y| format!("{:.0}", y))
        .axis_desc_style(("sans-serif", 18))
        .label_style(("sans-serif", 16))
        .x_labels(0)
        .draw()?;

    let male_style = COLOR_MALE_OR_CSMF.filled();
    let female_style = COLOR_FEMALE.filled();

    for i in 0..12 {
        let x = i as f64;
        let m_val = male_counts[i] as f64;
        let f_val = female_counts[i] as f64;
        if m_val > 0.0 {
            chart.draw_series(std::iter::once(Rectangle::new(
                [(x - 0.125, 0.0), (x + 0.125, m_val)],
                male_style,
            )))?;
        }
        if f_val > 0.0 {
            chart.draw_series(std::iter::once(Rectangle::new(
                [(x + 0.125, 0.0), (x + 0.375, f_val)],
                female_style,
            )))?;
        }
    }

    // Draw plot box frame
    let plot_left = left_margin;
    let plot_right = 960 - right_margin;
    let plot_top = top_margin;
    let plot_bottom = 464;
    upper.draw(&PathElement::new(
        vec![
            (plot_left, plot_top),
            (plot_right, plot_top),
            (plot_right, plot_bottom),
            (plot_left, plot_bottom),
            (plot_left, plot_top),
        ],
        BLACK.stroke_width(1),
    ))?;

    // Draw all 12 rotated age-group labels beneath each bar pair
    let x_span = 12.5_f64; // -0.5 to 12.0
    let plot_w = (plot_right - plot_left) as f64;
    let v_font = ("sans-serif", 16)
        .into_font()
        .transform(FontTransform::Rotate270)
        .color(&BLACK)
        .pos(Pos::new(HPos::Right, VPos::Center));

    for (idx, label) in AGE_BINS.iter().enumerate() {
        let tick_x = (idx as f64) + 0.125 + 0.5;
        let frac = tick_x / x_span;
        let px = plot_left + (frac * plot_w).round() as i32;
        lower.draw(&PathElement::new(
            vec![(px, 0), (px, 6)],
            BLACK.stroke_width(1),
        ))?;
        lower.draw(&Text::new(*label, (px, 12), v_font.clone()))?;
    }

    // Draw framed legend box (`male` / `female`) at the bottom center
    let leg_left = 340i32;
    let leg_right = 640i32;
    let leg_top = 185i32;
    let leg_bottom = 225i32;
    lower.draw(&Rectangle::new(
        [(leg_left, leg_top), (leg_right, leg_bottom)],
        RGBColor(0xD0, 0xD0, 0xD0).stroke_width(1),
    ))?;
    lower.draw(&Rectangle::new(
        [(leg_left + 15, leg_top + 12), (leg_left + 55, leg_top + 28)],
        COLOR_MALE_OR_CSMF.filled(),
    ))?;
    lower.draw(&Text::new(
        "male",
        (leg_left + 68, leg_top + 11),
        ("sans-serif", 17).into_font().color(&BLACK),
    ))?;
    lower.draw(&Rectangle::new(
        [(leg_left + 165, leg_top + 12), (leg_left + 205, leg_top + 28)],
        COLOR_FEMALE.filled(),
    ))?;
    lower.draw(&Text::new(
        "female",
        (leg_left + 218, leg_top + 11),
        ("sans-serif", 17).into_font().color(&BLACK),
    ))?;

    root.present()?;
    Ok(())
}

/// Render the GBD Level 1 CSMF pie chart (`gbd-level1-csmf.png`) at 960x720
/// matching upstream `output_prep.py::_graph_gbd_csmf`.
pub fn render_gbd_pie_chart(
    rows: &[(String, String, f64)],
    out_path: &Path,
) -> Result<()> {
    let root = BitMapBackend::new(out_path, (960, 720)).into_drawing_area();
    root.fill(&WHITE)?;

    let mut color_map = BTreeMap::new();
    color_map.insert("A", RGBColor(0xE7, 0x4C, 0x3C)); // #e74c3c
    color_map.insert("B", RGBColor(0x34, 0x98, 0xDB)); // #3498db
    color_map.insert("C", RGBColor(0x2E, 0xCC, 0x71)); // #2ecc71
    color_map.insert("X", RGBColor(0xD3, 0xD3, 0xD3)); // #D3D3D3

    let sizes: Vec<f64> = rows.iter().map(|(_, _, v)| (*v).max(0.0)).collect();
    let colors: Vec<RGBColor> = rows
        .iter()
        .map(|(code, _, _)| {
            color_map
                .get(code.as_str())
                .copied()
                .unwrap_or(RGBColor(0xD3, 0xD3, 0xD3))
        })
        .collect();

    let total: f64 = sizes.iter().sum::<f64>().max(1e-9);
    let center = (480i32, 360i32);
    let radius = 178.0_f64;

    // Upstream `ax.pie()` sweeps counter-clockwise starting at 0 radians (3-o'clock):
    // In bitmap coordinates (y downward), counter-clockwise means `py = center.1 - r * sin(ang)`.
    let mut start_angle = 0.0_f64;
    for (idx, val) in sizes.iter().enumerate() {
        let sweep = (*val / total) * std::f64::consts::TAU;
        if sweep <= 1e-6 {
            continue;
        }
        let steps = ((sweep * 80.0).ceil() as usize).max(8);
        let mut pts = Vec::with_capacity(steps + 2);
        pts.push(center);
        for s in 0..=steps {
            let ang = start_angle + sweep * (s as f64 / steps as f64);
            let px = center.0 + (radius * ang.cos()).round() as i32;
            let py = center.1 - (radius * ang.sin()).round() as i32;
            pts.push((px, py));
        }
        root.draw(&Polygon::new(pts, colors[idx].filled()))?;

        // Draw percentage (`%1.1f%%`) inside the wedge at 0.6 * radius
        let mid_ang = start_angle + sweep * 0.5;
        let pct = (*val / total) * 100.0;
        if pct >= 1.0 {
            let tx = center.0 + (radius * 0.60 * mid_ang.cos()).round() as i32;
            let ty = center.1 - (radius * 0.60 * mid_ang.sin()).round() as i32;
            let pct_font = ("sans-serif", 16)
                .into_font()
                .color(&BLACK)
                .pos(Pos::new(HPos::Center, VPos::Center));
            root.draw(&Text::new(format!("{pct:.1}%"), (tx, ty), pct_font))?;
        }

        // Draw category label outside the wedge at 1.12 * radius
        let lx = center.0 + (radius * 1.12 * mid_ang.cos()).round() as i32;
        let ly = center.1 - (radius * 1.12 * mid_ang.sin()).round() as i32;
        let h_pos = if mid_ang.cos() >= 0.0 {
            HPos::Left
        } else {
            HPos::Right
        };
        let lbl_font = ("sans-serif", 14)
            .into_font()
            .color(&BLACK)
            .pos(Pos::new(h_pos, VPos::Center));
        let raw_name = &rows[idx].1;
        if raw_name.starts_with("Comm") && raw_name.contains(", neo") {
            let parts: Vec<&str> = raw_name.splitn(2, ", neo").collect();
            let line1 = format!("{},", parts[0]);
            let line2 = format!("neo{}", parts.get(1).copied().unwrap_or(""));
            root.draw(&Text::new(line1, (lx, ly - 9), lbl_font.clone()))?;
            root.draw(&Text::new(line2, (lx, ly + 9), lbl_font))?;
        } else {
            root.draw(&Text::new(raw_name.as_str(), (lx, ly), lbl_font))?;
        }

        start_angle += sweep;
    }

    root.present()?;
    Ok(())
}
